// semantic-release configuration: every push to main (after CI passed, see .github/workflows/release.yml) looks at the
// commits since the last release tag and, when one of them is a feat / fix / perf (or a breaking change), releases the
// next version: CHANGELOG.md, <VersionPrefix> and the package validation baseline in src/Directory.Build.props, the
// eight NuGet packages and their SBOMs, a git tag v<version> and a GitHub release. How to write the commits:
// CONTRIBUTING.md, "Commit messages and releases".
// Versioning (fix / perf -> patch, feat -> minor, a breaking change -> major) and how a release works:
// docs/releasing.md.
//
//   npx semantic-release --dry-run --no-ci     what would the next release be? (needs GITHUB_TOKEN and push access)

// The Angular commit format (type(scope): subject), plus the `!` breaking-change marker from Conventional Commits
// (`feat!: ...`, `fix(cli)!: ...`). Same as the conventionalcommits preset's parser, plus the plural `BREAKING CHANGES`
// footer that the Angular guidelines also allow. Shared by the analyzer and the notes generator so both see the same
// commits.
const parserOpts = {
  headerPattern: /^(\w*)(?:\((.*)\))?!?: (.*)$/,
  breakingHeaderPattern: /^(\w*)(?:\((.*)\))?!: (.*)$/,
  headerCorrespondence: ["type", "scope", "subject"],
  noteKeywords: ["BREAKING CHANGE", "BREAKING CHANGES", "BREAKING-CHANGE"],
};

// Release-notes sections (conventional-changelog-conventionalcommits; the first matching entry wins, so the `deps`
// entries come before plain `fix` / `build`). Every release is a `##` heading, breaking changes get their own
// "⚠ BREAKING CHANGES" section and scopes are shown in bold (`**ui:** add a duration filter`). Hidden types don't
// appear in the notes (they don't release anything either, see the analyzer below), unless they carry a breaking change.
// Dependency updates: Renovate titles them fix(deps) (shipped, releases a patch) or build(deps) (samples, build tooling:
// no release, but listed when something else releases); build(deps-dev) stays hidden. See renovate.json.
const presetConfig = {
  types: [
    { type: "feat", section: "Features" },
    { type: "fix", scope: "deps", section: "Dependencies" },
    { type: "build", scope: "deps", section: "Dependencies" },
    { type: "fix", section: "Bug Fixes" },
    { type: "perf", section: "Performance" },
    { type: "revert", section: "Reverts" },
    { type: "docs", section: "Documentation", hidden: true },
    { type: "style", section: "Styles", hidden: true },
    { type: "chore", section: "Miscellaneous", hidden: true },
    { type: "refactor", section: "Refactoring", hidden: true },
    { type: "test", section: "Tests", hidden: true },
    { type: "build", section: "Build", hidden: true },
    { type: "ci", section: "CI", hidden: true },
  ],
};
// The preset orders sections by their first entry in `types`, which would put Dependencies above Bug Fixes.
const sectionOrder = ["Features", "Bug Fixes", "Performance", "Reverts", "Dependencies"];
const rank = (title) => (sectionOrder.includes(title) ? sectionOrder.indexOf(title) : sectionOrder.length);
const writerOpts = { commitGroupsSort: (a, b) => rank(a.title) - rank(b.title) };

// Kept at the top of CHANGELOG.md; @semantic-release/changelog adds each release below it. Must match the file.
const changelogTitle = `# Changelog

All notable changes to Labcoat are documented here. This file is generated by
[semantic-release](https://github.com/semantic-release/semantic-release) from the commit messages (see
[CONTRIBUTING.md](CONTRIBUTING.md#commit-messages-and-releases)): don't edit it by hand, write a good commit message
instead. Versions follow [Semantic Versioning](https://semver.org/spec/v2.0.0.html).`;

// LABCOAT_RELEASE_COMMIT=api: set by release.yml when the GitHub App token step ran (variable RELEASE_APP_ID);
// eng/release-commit.mjs then makes the release commit with createCommitOnBranch (docs/releasing.md, "How a release
// works"). Unset (local dry runs, no App configured): the git plugin, as before.
const releaseCommitMessage = "chore(release): ${nextRelease.version} [skip ci]\n\n${nextRelease.notes}";
const releaseCommitAssets = ["CHANGELOG.md", "src/Directory.Build.props"];
const releaseCommit =
  process.env.LABCOAT_RELEASE_COMMIT === "api"
    ? ["./eng/release-commit.mjs", { assets: releaseCommitAssets, message: releaseCommitMessage }]
    : ["@semantic-release/git", { assets: releaseCommitAssets, message: releaseCommitMessage }];

export default {
  // main releases normal versions (1.2.3: a NuGet release and a GitHub release). next and beta are optional
  // prerelease branches (1.3.0-beta.1, ...: NuGet and GitHub prereleases; create them when needed, see
  // docs/releasing.md, "Prereleases").
  branches: [
    "main",
    { name: "next", prerelease: true },
    { name: "beta", prerelease: true },
  ],
  tagFormat: "v${version}",
  plugins: [
    [
      "@semantic-release/commit-analyzer",
      {
        preset: "conventionalcommits",
        presetConfig,
        parserOpts,
        // No custom release rules: the analyzer's defaults (breaking -> major, feat -> minor, fix / perf / revert ->
        // patch; docs, chore, refactor, test, ci, build and style -> no release, whatever their scope: build(deps)
        // doesn't release).
      },
    ],
    [
      "@semantic-release/release-notes-generator",
      {
        preset: "conventionalcommits",
        presetConfig,
        parserOpts,
        writerOpts,
      },
    ],
    ["@semantic-release/changelog", { changelogFile: "CHANGELOG.md", changelogTitle }],
    [
      // Before the release commit: set the version, build the UI and pack, so a failing build stops the release
      // before anything is pushed. The pack validates the library packages against the previous release
      // (lastRelease.version; empty when there is none: no baseline), so an API break that has no suppression stops
      // the release too (docs/releasing.md, "Package validation").
      "@semantic-release/exec",
      {
        verifyConditionsCmd: "node eng/release.mjs verify --dry-run=${options.dryRun}",
        prepareCmd: "node eng/release.mjs prepare ${nextRelease.version} --baseline=${lastRelease.version}",
      },
    ],
    // The release commit: through the GitHub API as the "labcoat-release" GitHub App (signed by GitHub: "Verified")
    // when release.yml has the App's token, else @semantic-release/git (git commit + push with GITHUB_TOKEN, shown as
    // "Unverified"). Either way semantic-release then tags that commit v<version> and pushes the tag.
    releaseCommit,
    [
      "@semantic-release/github",
      {
        // The SBOMs written by eng/release.mjs prepare (docs/releasing.md, "SBOM"): <id>.<version>.spdx.json, the
        // SPDX 2.2 SBOM inside each .nupkg, and labcoat-ui.<version>.cdx.json, the UI's npm production dependencies.
        assets: [
          { path: "artifacts/*.nupkg", label: "NuGet packages" },
          { path: "artifacts/*.snupkg", label: "Symbol packages" },
          { path: "artifacts/*.spdx.json", label: "SBOM (SPDX 2.2) of a NuGet package" },
          { path: "artifacts/*.cdx.json", label: "SBOM (CycloneDX) of the UI's npm dependencies" },
        ],
        // Defaults kept on purpose: the PRs and issues in a release get a comment with the GitHub release and NuGet
        // links plus a `released` label (one comment per PR: squash merges keep that low), and a failed release opens
        // one issue ("The automated release is failing") that the next successful release closes. Set
        // successComment / failComment to false here if that gets noisy.
      },
    ],
    [
      // After the GitHub release (which carries the packages, so a failed push can be redone from there).
      "@semantic-release/exec",
      { publishCmd: "node eng/release.mjs publish ${nextRelease.version}" },
    ],
  ],
};
