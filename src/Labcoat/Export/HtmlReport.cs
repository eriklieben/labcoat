using System.Globalization;
using System.Text;

namespace Labcoat;

/// <summary>
/// Writes a run as a single self-contained HTML file: summary, the failed tests first (message, expected / actual
/// diff, stack trace, console output), then every project and class with its tests and durations, and filters (text,
/// outcome, project) in a small inline script. Light and dark follow <c>prefers-color-scheme</c> with Labcoat's default
/// theme tokens inlined.
/// <para>
/// Safe to open: every name, message and output is HTML-escaped (<see cref="ExportText.Html"/>), and the page's
/// Content-Security-Policy allows nothing but its own inline style and script (by hash): no external requests.
/// </para>
/// <para>
/// Sized for 20,000 tests: passed and skipped tests are one line each (no output); only the first
/// <see cref="MaxDetailedFailures"/> failures get their details, each part capped.
/// </para>
/// </summary>
public static partial class HtmlReport
{
    public const int MaxDetailedFailures = 500;
    public const int MaxMessageChars = 8192;
    public const int MaxStackChars = 16_384;
    public const int MaxOutputChars = 8192;

    private const string BucketFailed = "f";
    private const string BucketPassed = "p";
    private const string BucketSkipped = "s";
    private const string DetailsEnd = "</details>";
    private const string FailedText = "Failed";

    /// <summary>Writes the page to <paramref name="o"/>.</summary>
    public static void Write(RunExport export, TextWriter o)
    {
        var failed = export.Tests.Where(t => ExportKinds.IsFailed(t.Kind)).ToList();
        var failureIds = new Dictionary<ExportTest, int>(ReferenceEqualityComparer.Instance);
        for (var i = 0; i < failed.Count; i++) failureIds[failed[i]] = i;

        Head(export, o, failed.Count);
        o.Write("<body>\n");
        Summary(export, o, failed.Count);
        Toolbar(export, o);
        o.Write("<main>\n");
        Failures(failed, o);
        Projects(export, o, failureIds);
        o.Write("</main>\n");
        o.Write($"<footer>Generated by Labcoat {E(export.Version)} on {E(Utc(export.GeneratedAt))}. Run {E(export.Run.RunId)}.</footer>\n");
        o.Write($"<script>{ReportJs}</script>\n</body>\n</html>\n");
    }

    /// <summary>The page as a string.</summary>
    public static string ToHtml(RunExport export)
    {
        var sb = new StringBuilder(64 * 1024);
        using var w = new StringWriter(sb, CultureInfo.InvariantCulture);
        Write(export, w);
        return sb.ToString();
    }

    // ------------------------------------------------------------------ sections

    private static void Head(RunExport export, TextWriter o, int failed)
    {
        var style = Theme + "\n" + ReportCss;
        var verdict = failed > 0 ? $"{failed} failed" : $"{export.Tests.Count} tests";
        o.Write("<!doctype html>\n<html lang=\"en\">\n<head>\n<meta charset=\"utf-8\">\n");
        o.Write($"<meta http-equiv=\"Content-Security-Policy\" content=\"{ContentSecurityPolicy(style, ReportJs)}\">\n");
        o.Write("<meta name=\"referrer\" content=\"no-referrer\">\n");
        o.Write("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1\">\n");
        o.Write("<meta name=\"color-scheme\" content=\"light dark\">\n");
        o.Write($"<meta name=\"generator\" content=\"Labcoat {E(export.Version)}\">\n");
        o.Write($"<title>{E(export.WorkspaceName)} · {E(verdict)} · Labcoat test report</title>\n");
        o.Write($"<style>{style}</style>\n</head>\n");
    }

    private static void Summary(RunExport export, TextWriter o, int failed)
    {
        var run = export.Run;
        var kinds = export.Tests.Select(t => t.Kind).ToList();
        var passed = kinds.Count(k => k == ExportKind.Passed);
        var skipped = kinds.Count(k => k == ExportKind.Skipped);
        var notRun = kinds.Count(k => k == ExportKind.NotRun) + Math.Max(0, (run.NotRun ?? 0) - kinds.Count(k => k == ExportKind.NotRun));
        var quarantined = kinds.Count(k => k == ExportKind.QuarantinedFailure);

        o.Write("<header>\n<div class=\"top\"><span class=\"brand\">Labcoat</span>");
        o.Write($"<h1>Test report: {E(export.WorkspaceName)}</h1></div>\n");
        var meta = new List<string> { $"Started {Utc(run.StartedAt)}" };
        if (run.DurationMs is { } ms) meta.Add($"took {Duration(ms)}");
        meta.Add(run.Scope == "subset" ? $"partial run ({run.Total} selected)" : "all tests");
        meta.Add($"trigger: {run.Trigger ?? "user"}");
        meta.Add($"{export.Projects.Count} project{Plural(export.Projects.Count)}");
        o.Write($"<p class=\"meta\">{E(string.Join(" · ", meta))}</p>\n");
        Banner(export, o, failed, passed);
        o.Write("<dl class=\"cards\">\n");
        Card(o, "Total", kinds.Count, null);
        Card(o, "Passed", passed, "c-p");
        Card(o, FailedText, failed, failed > 0 ? "c-f" : null);
        Card(o, "Skipped", skipped, skipped > 0 ? "c-s" : null);
        if (notRun > 0) Card(o, "Not run", notRun, "c-s");
        if (quarantined > 0) Card(o, "Quarantined", quarantined, "c-s");
        o.Write($"<div class=\"card\"><dt>Duration</dt><dd>{E(Duration(run.DurationMs ?? export.Tests.Sum(t => t.DurationMs ?? 0)))}</dd></div>\n");
        o.Write("</dl>\n</header>\n");
    }

    private static void Banner(RunExport export, TextWriter o, int failed, int passed)
    {
        var run = export.Run;
        string tone, text;
        if (failed > 0) (tone, text) = ("bad", $"{failed} test{Plural(failed)} failed");
        else if (run.Aborted == true) (tone, text) = ("warn", "The run was aborted");
        else if (run.Cancelled == true) (tone, text) = ("warn", "The run was cancelled");
        else if (export.Tests.Count == 0) (tone, text) = ("warn", "No test results in this run");
        else (tone, text) = ("ok", passed == export.Tests.Count ? $"All {passed} tests passed" : $"No failures ({passed} passed)");
        var detail = run.Aborted == true ? run.AbortReason : null;
        o.Write($"<div class=\"banner {tone}\" role=\"status\">{E(text)}");
        if (!string.IsNullOrEmpty(detail)) o.Write($" <span class=\"muted\">{E(detail)}</span>");
        o.Write("</div>\n");
    }

    private static void Card(TextWriter o, string label, int value, string? tone) =>
        o.Write($"<div class=\"card\"><dt>{label}</dt><dd{(tone is null ? "" : $" class=\"{tone}\"")}>{value.ToString("N0", CultureInfo.InvariantCulture)}</dd></div>\n");

    private static void Toolbar(RunExport export, TextWriter o)
    {
        o.Write("<div class=\"toolbar\" role=\"search\" aria-label=\"Filter tests\">\n");
        o.Write("<label class=\"visually-hidden\" for=\"q\">Filter tests by name or class</label>");
        o.Write("<input id=\"q\" type=\"search\" placeholder=\"Filter tests by name or class\" autocomplete=\"off\" spellcheck=\"false\">\n");
        o.Write("<fieldset class=\"outcomes\"><legend class=\"visually-hidden\">Outcomes</legend>");
        o.Write($"<label><input type=\"checkbox\" data-bucket=\"{BucketFailed}\" checked> Failed</label>");
        o.Write($"<label><input type=\"checkbox\" data-bucket=\"{BucketPassed}\" checked> Passed</label>");
        o.Write($"<label><input type=\"checkbox\" data-bucket=\"{BucketSkipped}\" checked> Skipped</label></fieldset>\n");
        if (export.Projects.Count > 1)
        {
            o.Write("<label>Project <select id=\"proj\"><option value=\"\">All</option>");
            foreach (var p in export.Projects) o.Write($"<option value=\"{E(p.Id)}\">{E(p.Name)}</option>");
            o.Write("</select></label>\n");
        }
        o.Write("<button type=\"button\" id=\"expand\">Expand all</button><button type=\"button\" id=\"collapse\">Collapse all</button>\n");
        o.Write($"<span class=\"shown\" id=\"shown\" aria-live=\"polite\">{export.Tests.Count} tests</span>\n</div>\n");
    }

    private static void Failures(List<ExportTest> failed, TextWriter o)
    {
        if (failed.Count == 0) return;
        o.Write($"<section class=\"fails\" aria-labelledby=\"h-failed\">\n<h2 id=\"h-failed\">Failed ({failed.Count})</h2>\n");
        for (var i = 0; i < failed.Count && i < MaxDetailedFailures; i++) FailureBlock(failed[i], i, o);
        if (failed.Count > MaxDetailedFailures)
            o.Write($"<p class=\"note\">{failed.Count - MaxDetailedFailures} more failed tests are listed below with their first message line (details are kept for the first {MaxDetailedFailures}).</p>\n");
        o.Write("</section>\n");
    }

    private static void FailureBlock(ExportTest t, int index, TextWriter o)
    {
        o.Write($"<details class=\"fail\" id=\"f{index}\" data-b=\"{BucketFailed}\" data-p=\"{E(t.ProjectId)}\" open>\n<summary>");
        o.Write($"<span class=\"n\"><span class=\"visually-hidden\">Failed: </span>{E(t.Name)}</span>");
        o.Write($"<span class=\"muted mono\">{E(t.ClassFullName)}</span><span class=\"muted\">{E(t.ProjectId)}</span>");
        o.Write($"<span class=\"d\">{E(TestDuration(t))}</span></summary>\n<div class=\"body\">\n");
        var kind = t.Kind == ExportKind.Error ? "Error" : "Assertion failed";
        var type = string.IsNullOrEmpty(t.ErrorType) ? kind : $"{kind} · {t.ErrorType}";
        o.Write($"<div class=\"label\">{E(type)}</div>\n");
        var message = string.IsNullOrEmpty(t.ErrorMessage) ? DefaultMessage(t) : t.ErrorMessage;
        o.Write($"<pre class=\"msg\">{E(ExportText.Cap(message, MaxMessageChars))}</pre>\n");
        Diff(t, o);
        Block(o, "Stack trace", t.StackTrace, MaxStackChars);
        Block(o, "Standard output", t.StdOut, MaxOutputChars);
        Block(o, "Standard error", t.StdErr, MaxOutputChars);
        o.Write("</div>\n" + DetailsEnd + "\n");
    }

    private static void Diff(ExportTest t, TextWriter o)
    {
        if (AssertionDiff.Parse(t.ErrorMessage) is not { } values) return;
        var expected = ExportText.Cap(values.Expected, MaxMessageChars);
        var actual = ExportText.Cap(values.Actual, MaxMessageChars);
        if (expected == actual || AssertionDiff.Lines(expected, actual) is not { } lines) return;
        o.Write("<div class=\"label\">Diff <span class=\"muted\">(− expected, + actual)</span></div>\n<pre class=\"diff\">");
        foreach (var line in lines)
        {
            var cls = line.Op switch { '-' => " class=\"del\"", '+' => " class=\"add\"", _ => "" };
            o.Write($"<span{cls}>{(line.Op == ' ' ? "  " : line.Op + " ")}{E(line.Text)}</span>");
        }
        o.Write("</pre>\n");
    }

    private static void Block(TextWriter o, string label, string? text, int max)
    {
        if (string.IsNullOrWhiteSpace(text)) return;
        o.Write($"<div class=\"label\">{label}</div>\n<pre>{E(ExportText.Cap(text, max))}</pre>\n");
    }

    private static void Projects(RunExport export, TextWriter o, Dictionary<ExportTest, int> failureIds)
    {
        o.Write("<section aria-labelledby=\"h-all\">\n<h2 id=\"h-all\">All tests</h2>\n");
        if (export.Tests.Count == 0) o.Write("<p class=\"note\">This run has no test results.</p>\n");
        var byProject = export.Tests.ToLookup(t => t.ProjectId, StringComparer.Ordinal);
        foreach (var p in export.Projects)
        {
            var tests = byProject[p.Id].ToList();
            o.Write($"<details class=\"proj\" data-p=\"{E(p.Id)}\" open>\n<summary>{E(p.Name)} <span class=\"muted\">{E(Counts(tests))}");
            if (p.TargetFramework is { } tfm) o.Write($" · {E(tfm)}");
            o.Write($" · {E(Duration(tests.Sum(t => t.DurationMs ?? 0)))}</span></summary>\n");
            foreach (var group in tests.GroupBy(t => t.ClassFullName, StringComparer.Ordinal))
                ClassGroup(group.Key, group.ToList(), o, failureIds);
            o.Write(DetailsEnd + "\n");
        }
        o.Write("</section>\n");
    }

    private static void ClassGroup(string name, List<ExportTest> tests, TextWriter o, Dictionary<ExportTest, int> failureIds)
    {
        var open = tests.Exists(t => ExportKinds.IsFailed(t.Kind)) ? " open" : "";
        var shown = name.Length > 0 ? name : "(no class)";
        o.Write($"<details class=\"cls\" data-g=\"{E(name)}\"{open}><summary><span class=\"mono\">{E(shown)}</span> ");
        o.Write($"<span class=\"muted\">{E(Counts(tests))} · {E(Duration(tests.Sum(t => t.DurationMs ?? 0)))}</span></summary>\n<ul class=\"rows\">\n");
        foreach (var t in tests) Row(t, o, failureIds);
        o.Write("</ul>" + DetailsEnd + "\n");
    }

    private static void Row(ExportTest t, TextWriter o, Dictionary<ExportTest, int> failureIds)
    {
        var kind = t.Kind;
        var bucket = Bucket(kind);
        o.Write($"<li class=\"r {bucket}\" data-b=\"{bucket}\"><span class=\"visually-hidden\">{StatusText(kind)}: </span>");
        if (failureIds.TryGetValue(t, out var id) && id < MaxDetailedFailures) o.Write($"<a class=\"n\" href=\"#f{id}\">{E(t.Name)}</a>");
        else o.Write($"<span class=\"n\">{E(t.Name)}</span>");
        var why = kind switch
        {
            ExportKind.Passed => null,
            ExportKind.Failure or ExportKind.Error => id >= MaxDetailedFailures ? ExportText.FirstLine(t.ErrorMessage) : null,
            _ => ExportKinds.SkipReason(t),
        };
        if (!string.IsNullOrEmpty(why)) o.Write($"<span class=\"why\">{E(why)}</span>");
        o.Write($"<span class=\"d\">{E(TestDuration(t))}</span></li>\n");
    }

    // ------------------------------------------------------------------ helpers

    private static string E(string? s) => ExportText.Html(s);

    private static string Bucket(ExportKind k) => k switch
    {
        ExportKind.Passed => BucketPassed,
        ExportKind.Failure or ExportKind.Error => BucketFailed,
        _ => BucketSkipped,
    };

    private static string StatusText(ExportKind k) => k switch
    {
        ExportKind.Passed => "Passed",
        ExportKind.Failure or ExportKind.Error => FailedText,
        ExportKind.NotRun => "Not run",
        ExportKind.QuarantinedFailure => "Quarantined",
        _ => "Skipped",
    };

    private static string Counts(List<ExportTest> tests)
    {
        var failed = tests.Count(t => ExportKinds.IsFailed(t.Kind));
        var passed = tests.Count(t => t.Kind == ExportKind.Passed);
        var other = tests.Count - failed - passed;
        var parts = new List<string> { $"{tests.Count} test{Plural(tests.Count)}" };
        if (failed > 0) parts.Add($"{failed} failed");
        if (passed > 0 && passed < tests.Count) parts.Add($"{passed} passed");
        if (other > 0) parts.Add($"{other} skipped");
        return string.Join(", ", parts);
    }

    private static string DefaultMessage(ExportTest t) => t.Outcome == Outcome.TimedOut ? "Timed out" : FailedText;

    private static string TestDuration(ExportTest t) => t.DurationMs is { } ms ? Duration(ms) : "";

    /// <summary>"12 ms", "1.4 s", "2 min 05 s".</summary>
    internal static string Duration(double ms)
    {
        if (ms < 1000) return $"{Math.Round(ms).ToString(CultureInfo.InvariantCulture)} ms";
        if (ms < 60_000) return $"{(ms / 1000).ToString("0.0", CultureInfo.InvariantCulture)} s";
        var t = TimeSpan.FromMilliseconds(ms);
        return $"{(int)t.TotalMinutes} min {t.Seconds:00} s";
    }

    /// <summary>"2026-10-11 08:15 UTC" (the ISO string itself when it does not parse).</summary>
    internal static string Utc(string iso) =>
        DateTimeOffset.TryParse(iso, CultureInfo.InvariantCulture, DateTimeStyles.AssumeUniversal, out var at)
            ? at.UtcDateTime.ToString("yyyy-MM-dd HH:mm 'UTC'", CultureInfo.InvariantCulture)
            : iso;

    private static string Plural(int n) => n == 1 ? "" : "s";
}
