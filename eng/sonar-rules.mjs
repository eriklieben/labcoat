// Writes src/sonar.globalconfig: the C# rules of the project's SonarQube Cloud quality profile as build warnings, every
// other Sonar C# rule off, so `dotnet build` (and CI's -warnaserror build) reports what SonarQube Cloud would. The
// SonarAnalyzer.CSharp package's own defaults differ from the profile (S107 and S3776 are off there, for one).
// Run it again when SonarQube Cloud updates the profile; the rules' parameters are the profile's defaults (checked
// here: a changed parameter is an error, since a .globalconfig can't set one).
//
//   node eng/sonar-rules.mjs            needs no token: the profile and its rules are public
import { writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const api = "https://sonarcloud.io/api";
const organization = "eriklieben";
const project = "eriklieben_labcoat";

/** The rule parameters SonarAnalyzer.CSharp uses without a SonarLint.xml: the profile must not change them. */
const defaultParams = {
  S107: { max: "7" },
  S110: { max: "5" },
  S1192: { threshold: "3" },
  S1479: { maximum: "30" },
  S2436: { max: "2", maxMethod: "3" },
  S3776: { threshold: "15", propertyThreshold: "3" },
};

async function get(url) {
  const response = await fetch(api + url);
  if (!response.ok) throw new Error(`${url}: ${response.status} ${response.statusText}`);
  return response.json();
}

/** Every page of a rules/search. */
async function rules(query) {
  const all = [];
  for (let page = 1; ; page++) {
    const result = await get(`/rules/search?organization=${organization}&repositories=csharpsquid&ps=500&p=${page}&${query}`);
    all.push(result);
    if (page * 500 >= result.total) return all;
  }
}

const { profiles } = await get(`/qualityprofiles/search?organization=${organization}&project=${project}&language=cs`);
const profile = profiles[0];
const active = new Map();
for (const page of await rules(`qprofile=${profile.key}&activation=true&f=name,actives`)) {
  for (const rule of page.rules) active.set(rule.key.replace("csharpsquid:", ""), rule.name);
  for (const [key, activations] of Object.entries(page.actives ?? {})) {
    const id = key.replace("csharpsquid:", "");
    for (const { key: name, value } of activations.flatMap((a) => a.params ?? [])) {
      const expected = defaultParams[id]?.[name];
      if (expected !== undefined && expected !== value)
        throw new Error(`${id}: the profile sets ${name} = ${value} (default ${expected}); a .globalconfig can't, see SonarLint.xml.`);
    }
  }
}
const all = (await rules("f=name")).flatMap((page) => page.rules.map((r) => r.key.replace("csharpsquid:", "")));
const byNumber = (a, b) => Number(a.slice(1)) - Number(b.slice(1));

const lines = [
  "# Generated by eng/sonar-rules.mjs from the SonarQube Cloud quality profile of this project: run it again to update.",
  `# Profile: ${profile.name} (${active.size} C# rules), rules updated ${profile.rulesUpdatedAt}.`,
  "is_global = true",
  "",
  "# The profile's rules: warnings, which CI's -warnaserror build turns into errors.",
  ...[...active.keys()].sort(byNumber).map((id) => `dotnet_diagnostic.${id}.severity = warning # ${active.get(id)}`),
  "",
  "# The other Sonar C# rules: off, as in SonarQube Cloud.",
  ...all.filter((id) => !active.has(id)).sort(byNumber).map((id) => `dotnet_diagnostic.${id}.severity = none`),
  "",
];
const file = path.join(root, "src", "sonar.globalconfig");
writeFileSync(file, lines.join("\n"));
console.log(`${path.relative(root, file)}: ${active.size} rules on, ${all.length - active.size} off (${profile.name}).`);
